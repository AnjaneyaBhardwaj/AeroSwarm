"""Mesh-independence study for the OpenFOAM T2 tier (milestone 5 part 3).

    uv run python scripts/of_mesh_study.py run --parallel 4   # needs OpenFOAM; writes evals/openfoam_mesh_study.json
    uv run python scripts/of_mesh_study.py report             # appends the generated part of docs/OPENFOAM_MESH.md

One parameter at a time from the default mesh (`solver.DEFAULT_MESH`): cells around the section, first-cell
height, wall-normal growth, far-field radius; on NACA 0012 (Re 6e6, alpha 10, 0.2% TE) and the hard preset's
witness design (Re 3e5, alpha 8.75). Fully turbulent k-omega SST, default solver settings. Work files go to
runs/of_mesh_study/.
"""

from __future__ import annotations

import argparse
import dataclasses
import json
import sys
import time
from multiprocessing import Pool
from pathlib import Path

from swarm.cad.build import main_section, naca4
from swarm.run import HARD_SPEC
from swarm.solvers.openfoam import exec as foam
from swarm.solvers.openfoam.solver import DEFAULT_MESH, evaluate
from swarm.state import WingParams, speed_for_reynolds

CACHE = Path("evals/openfoam_mesh_study.json")
DOC = Path("docs/OPENFOAM_MESH.md")
WORK = Path("runs/of_mesh_study")
VARIANTS: dict[str, tuple[float, ...]] = {
    "n_surface": (160, 240, 360, 480),
    "first_cell": (1e-5, 2e-5, 4e-5),
    "growth": (1.08, 1.12, 1.16),
    "farfield": (50.0, 100.0, 150.0),
}
CASES = {
    "naca0012_re6e6_a10": (
        WingParams(main_camber=0.0, main_camber_pos=0.4, main_thickness=0.12, alpha_deg=10.0),
        HARD_SPEC.model_copy(update={"speed_mps": speed_for_reynolds(6e6, HARD_SPEC.car.chord_mm), "rulebook": "none"}),
        lambda: naca4(0.0, 0.4, 0.12, n=201, te_thick=0.002),
    ),
    "witness_re3e5": (
        WingParams(main_camber=0.085, main_camber_pos=0.35, main_thickness=0.135, alpha_deg=8.75),
        HARD_SPEC,
        None,
    ),
}


def jobs() -> list[tuple[str, str, float]]:
    out = []
    for case in CASES:
        out.append((case, "default", 0.0))
        for name, values in VARIANTS.items():
            for v in values:
                if v != getattr(DEFAULT_MESH, name):
                    out.append((case, name, v))
    return out


def one(job: tuple[str, str, float]) -> dict:
    case, name, value = job
    params, spec, coords = CASES[case]
    mesh = (
        DEFAULT_MESH
        if name == "default"
        else dataclasses.replace(DEFAULT_MESH, **{name: type(getattr(DEFAULT_MESH, name))(value)})
    )
    if name == "farfield":
        mesh = dataclasses.replace(mesh, max_step=max(mesh.max_step, value / 25))
    tag = "default" if name == "default" else f"{name}_{value:g}"
    t0 = time.time()
    r = evaluate(params, spec, WORK / case, mesh=mesh, tag=tag, coords=coords() if coords else main_section(params))
    row = {
        "case": case,
        "param": name,
        "value": value if name != "default" else None,
        "status": r.status,
        "cl": r.cl,
        "cd": r.cd,
        "te_sep": r.bl.te_separation_xc if r.bl else None,
        "cells": r.mesh.get("cells"),
        "yplus": r.yplus,
        "drop": r.residual_drop_orders,
        "wall_s": round(time.time() - t0, 1),
    }
    print(f"{case} {tag}: {r.status} Cl {r.cl} Cd {r.cd}", flush=True)
    return row


def cmd_run(parallel: int) -> None:
    if not foam.available():
        sys.exit("OpenFOAM not found")
    with Pool(parallel) as pool:
        rows = pool.map(one, jobs())
    CACHE.write_text(
        json.dumps(
            {"date": time.strftime("%Y-%m-%d"), "default": dataclasses.asdict(DEFAULT_MESH), "rows": rows}, indent=1
        )
    )
    print(f"wrote {CACHE}")


def markdown(data: dict) -> str:
    d = data["default"]
    out = [
        "# OpenFOAM T2 tier: mesh independence",
        "",
        f"Generated by `scripts/of_mesh_study.py report` from `evals/openfoam_mesh_study.json` (run {data['date']}). "
        f"Default mesh: {d['n_surface']} cells around, first cell {d['first_cell']:g} c, growth {d['growth']}, "
        f"far field {d['farfield']:g} c. One parameter changed at a time; Delta = change from the default case. "
        "k-omega SST, fully turbulent.",
        "",
    ]
    for case in CASES:
        rows = [r for r in data["rows"] if r["case"] == case]
        base = next((r for r in rows if r["param"] == "default"), None)
        out += [f"## {case}", "", "| parameter | value | cells | status | Cl | Cd | ΔCl | ΔCd (%) | y+ mean | TE sep |",
                "|---|---|---|---|---|---|---|---|---|---|"]  # fmt: skip
        for r in sorted(rows, key=lambda r: (r["param"] != "default", r["param"], r["value"] or 0)):
            dcl = dcd = "—"
            if base and r["cl"] is not None and base["cl"] is not None:
                dcl = f"{r['cl'] - base['cl']:+.4f}"
                dcd = f"{100 * (r['cd'] - base['cd']) / base['cd']:+.1f}"
            val = "—" if r["value"] is None else f"{r['value']:g}"
            yp = "—" if not r["yplus"] else f"{r['yplus'][1]:.2f}"
            cl = "—" if r["cl"] is None else f"{r['cl']:.4f}"
            cd = "—" if r["cd"] is None else f"{r['cd']:.5f}"
            sep = "—" if r["te_sep"] is None else f"{r['te_sep']:.2f}"
            out.append(
                f"| {r['param']} | {val} | {r['cells']} | {r['status']} | {cl} | {cd} | {dcl} | {dcd} | {yp} | {sep} |"
            )
        out.append("")
    return "\n".join(out)


def cmd_report() -> None:
    data = json.loads(CACHE.read_text())
    keep = ""
    if DOC.exists() and "## Findings" in DOC.read_text():
        keep = "\n" + DOC.read_text()[DOC.read_text().index("## Findings") :]
    DOC.write_text(markdown(data) + keep)
    print(f"wrote {DOC}")


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    r = sub.add_parser("run")
    r.add_argument("--parallel", type=int, default=4)
    sub.add_parser("report")
    a = ap.parse_args()
    cmd_run(a.parallel) if a.cmd == "run" else cmd_report()
