"""Validation of the T2 OpenFOAM tier (milestone 5, part 1; swarm/solvers/openfoam).

    uv run python scripts/of_validate.py run --parallel 3   # needs OpenFOAM; writes evals/openfoam_validation.json
    uv run python scripts/of_validate.py report             # writes docs/OPENFOAM.md from the cache

Cases:
- NACA 0012, Re 6e6, alpha 0 / 10 / 14 deg, fully turbulent (the NASA Turbulence Modeling Resource 2D
  validation case). The section is generated with a 0.2% c trailing-edge base (the reference airfoil is sharp;
  the project's 0.7% base adds base drag). Reference at alpha 10: CFL3D SST Cl ~ 1.078, Cd ~ 0.0124, as quoted
  by SimFlow's validation page (the NASA site was not reachable from this environment).
- Hard-preset designs at Re 3e5 (the project's operating point), compared with XFoil (e^N transition).
Work files go to runs/of_validate/ (not committed).
"""

from __future__ import annotations

import argparse
import json
import sys
import time
from multiprocessing import Pool
from pathlib import Path

from swarm.cad.build import build, naca4
from swarm.run import HARD_SPEC
from swarm.solvers import xfoil
from swarm.solvers.openfoam import exec as foam
from swarm.solvers.openfoam.solver import DEFAULT_MESH, evaluate
from swarm.state import WingParams, speed_for_reynolds

CACHE = Path("evals/openfoam_validation.json")
DOC = Path("docs/OPENFOAM.md")
WORK = Path("runs/of_validate")
NACA_SPEC = HARD_SPEC.model_copy(
    update={"speed_mps": speed_for_reynolds(6e6, HARD_SPEC.car.chord_mm), "rulebook": "none"}
)
REFERENCE = {
    10.0: {"cl": 1.078, "cd": 0.0124, "source": "CFL3D SST via help.sim-flow.com/validation/naca-0012-airfoil"}
}
PROJECT = [
    WingParams(main_camber=0.085, main_camber_pos=0.35, main_thickness=0.135, alpha_deg=8.75),  # session-12 witness
    WingParams(main_camber=0.06, main_camber_pos=0.4, main_thickness=0.13, alpha_deg=4.0),
    WingParams(main_camber=0.04, main_camber_pos=0.4, main_thickness=0.13, alpha_deg=2.0),
]


def jobs() -> list[dict]:
    alphas = (0.0, 10.0, 14.0)  # 14: the WingParams bound
    out = [{"name": f"naca0012_a{a:g}", "kind": "naca0012", "alpha": a} for a in alphas]
    out += [{"name": f"project_{p.cid}", "kind": "project", "params": p.model_dump()} for p in PROJECT]
    return out


def one(job: dict) -> dict:
    try:
        return _one(job)
    except Exception as e:  # one case's error is recorded, not the batch's end
        print(f"{job['name']}: error {e!r}", flush=True)
        return {**job, "error": repr(e)[:300]}


def _one(job: dict) -> dict:
    t0 = time.time()
    if job["kind"] == "naca0012":
        p = WingParams(main_camber=0.0, main_camber_pos=0.4, main_thickness=0.12, alpha_deg=job["alpha"])
        r = evaluate(p, NACA_SPEC, WORK, coords=naca4(0.0, 0.4, 0.12, n=201, te_thick=0.002), tag="naca0012")
        ref = REFERENCE.get(job["alpha"])
        xf = None
    else:
        p = WingParams(**job["params"])
        r = evaluate(p, HARD_SPEC, WORK)
        g = build(p, HARD_SPEC, WORK / "xfoil")
        rx = None
        for lvl in range(xfoil.MAX_LEVEL + 1):
            rx = xfoil.evaluate(p, HARD_SPEC, g.coords_path, WORK / "xfoil", lvl)
            if rx.status == "converged":
                break
        xf = {"cl": rx.cl, "cd": rx.cd, "te_sep": rx.bl.te_separation_xc if rx.bl else None} if rx.cl else None
        ref = None
    row = {
        **job,
        "params": p.model_dump(),
        "status": r.status,
        "signature": r.failure_signature,
        "cl": r.cl,
        "cd": r.cd,
        "upright_cl": None if r.cl is None else -r.cl,
        "residual_drop_orders": r.residual_drop_orders,
        "coeff_rel_std": r.coeff_rel_std_window,
        "yplus": r.yplus,
        "te_sep": r.bl.te_separation_xc if r.bl else None,
        "mesh": {k: r.mesh.get(k) for k in ("cells", "max_non_ortho", "max_skewness", "ok", "farfield")},
        "reference": ref,
        "xfoil": xf,
        "wall_s": round(time.time() - t0, 1),
    }
    print(f"{job['name']}: {r.status} Cl {r.cl} Cd {r.cd} ({row['wall_s']:.0f} s)", flush=True)
    return row


def cmd_run(parallel: int) -> None:
    if not foam.available():
        sys.exit("OpenFOAM not found (apt-get install openfoam; see .claude/hooks/session-start.sh)")
    with Pool(parallel) as pool:
        rows = pool.map(one, jobs())
    meta = {"date": time.strftime("%Y-%m-%d"), "openfoam": "ESI v1912 (Ubuntu package)", "mesh": DEFAULT_MESH.__dict__}
    CACHE.parent.mkdir(parents=True, exist_ok=True)
    CACHE.write_text(json.dumps({"meta": meta, "rows": rows}, indent=1))
    print(f"wrote {CACHE}")


def _f(x, fmt="{:.4f}"):
    return "—" if x is None else fmt.format(x)


def markdown(rows: list[dict], meta: dict) -> str:
    m = meta["mesh"]
    out = [
        "# OpenFOAM T2 tier: validation",
        "",
        f"Generated by `scripts/of_validate.py report` from `evals/openfoam_validation.json` (run {meta['date']}, "
        f"{meta['openfoam']}). simpleFoam, k-omega SST (fully turbulent), O-grid {m['n_surface']} cells around, "
        f"first cell {m['first_cell']:g} c, growth {m['growth']}, far field {m['farfield']:g} c. Forces from the "
        "wall-adjacent cells (`swarm/solvers/openfoam/forces.py`). Upright frame for NACA 0012 (positive lift); "
        "race-car Cl (negative = downforce) for the project designs.",
        "",
        "## NACA 0012, Re 6e6",
        "",
        "| alpha | status | Cl | Cd | reference Cl / Cd | p / U residual drop (orders) | y+ mean (max) | cells "
        "| wall clock |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        if r["kind"] != "naca0012" or "error" in r:
            continue
        ref = r["reference"]
        refs = f"{ref['cl']} / {ref['cd']}" if ref else "—"
        d = r["residual_drop_orders"] or {}
        yp = r["yplus"]
        out.append(
            f"| {r['alpha']:g} | {r['status']} | {_f(r['upright_cl'])} | {_f(r['cd'], '{:.5f}')} | {refs} "
            f"| {_f(d.get('p'), '{:.1f}')} / {_f(d.get('U'), '{:.1f}')} "
            f"| {_f(yp[1] if yp else None, '{:.2f}')} ({_f(yp[2] if yp else None, '{:.2f}')}) "
            f"| {r['mesh']['cells']} | {r['wall_s']:.0f} s |"
        )
    out += [
        "",
        "## Project designs, Re 3e5 (hard preset): OpenFOAM SST vs XFoil",
        "",
        "| design (m, p, t, alpha) | OpenFOAM Cl | Cd | TE separation from | XFoil Cl | Cd | TE separation from |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        if r["kind"] != "project" or "error" in r:
            continue
        p, x = r["params"], r["xfoil"] or {}
        out.append(
            f"| {p['main_camber']}, {p['main_camber_pos']}, {p['main_thickness']}, {p['alpha_deg']} "
            f"| {_f(r['cl'])} | {_f(r['cd'], '{:.5f}')} | {_f(r['te_sep'], '{:.2f}')} "
            f"| {_f(x.get('cl'))} | {_f(x.get('cd'), '{:.5f}')} | {_f(x.get('te_sep'), '{:.2f}')} |"
        )
    out.append("")
    return "\n".join(out)


def cmd_report() -> None:
    data = json.loads(CACHE.read_text())
    keep = ""
    if DOC.exists() and "## Findings" in DOC.read_text():  # hand-written; survives regeneration
        keep = "\n" + DOC.read_text()[DOC.read_text().index("## Findings") :]
    DOC.write_text(markdown(data["rows"], data["meta"]) + keep)
    print(f"wrote {DOC}")


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    r = sub.add_parser("run")
    r.add_argument("--parallel", type=int, default=3)
    sub.add_parser("report")
    a = ap.parse_args()
    cmd_run(a.parallel) if a.cmd == "run" else cmd_report()
